// Generate 24 months time-series helper
export function generateTimeSeries(
  baseNdvi: number,
  deltaNdvi: number,
  baseNdwi: number,
  deltaNdwi: number,
  isAnomaly: boolean = false
): TimeSeriesPoint[] {
  const months = [
    'Oct 24', 'Nov 24', 'Dec 24', 'Jan 25', 'Feb 25', 'Mar 25',
    'Apr 25', 'May 25', 'Jun 25', 'Jul 25', 'Aug 25', 'Sep 25',
    'Oct 25', 'Nov 25', 'Dec 25', 'Jan 26', 'Feb 26', 'Mar 26',
    'Apr 26', 'May 26', 'Jun 26', 'Jul 26', 'Aug 26', 'Sep 26'
  ];

  return months.map((month, idx) => {
    // Monsoon seasonal pulse: Jul-Oct (idx 8-11, 20-23)
    const isMonsoon = (idx >= 8 && idx <= 12) || (idx >= 20 && idx <= 23);
    const progress = idx / 23;
    
    let ndviVal = baseNdvi + (deltaNdvi * progress) + (isMonsoon ? 0.08 : -0.04);
    let ndwiVal = baseNdwi + (deltaNdwi * progress) + (isMonsoon ? 0.18 : -0.08);

    if (isAnomaly && idx > 14) {
      // Simulate erratic anomaly / drop
      ndviVal -= 0.12;
      ndwiVal -= 0.15;
    }

    // Clamp between -1 and 1
    ndviVal = Math.max(-0.2, Math.min(0.85, parseFloat(ndviVal.toFixed(3))));
    ndwiVal = Math.max(-0.5, Math.min(0.7, parseFloat(ndwiVal.toFixed(3))));

    const rainfall = isMonsoon ? Math.floor(90 + Math.random() * 110) : Math.floor(Math.random() * 18);
    const soilMoisture = Math.max(0.05, Math.min(0.9, parseFloat(((ndviVal + ndwiVal + 0.5) / 2).toFixed(2))));

    const [m, y] = month.split(' ');
    const yearNum = y === '24' ? '2024' : y === '25' ? '2025' : '2026';
    const monthMap: Record<string, string> = {
      Oct: '10', Nov: '11', Dec: '12', Jan: '01', Feb: '02', Mar: '03',
      Apr: '04', May: '05', Jun: '06', Jul: '07', Aug: '08', Sep: '09'
    };

    return {
      date: `${yearNum}-${monthMap[m]}-15`,
      monthLabel: month,
      ndvi: ndviVal,
      ndwi: ndwiVal,
      soilMoistureIndex: soilMoisture,
      rainfallMm: rainfall
    };
  });
}

// Explainable Score Calculator formula:
// Score = w1*NDVI_gain + w2*NDWI_presence + w3*Structure_evidence + w4*Consistency_factor, normalized 0-100
export function computeWatershedScore(
  deltaNdvi: number,
  postNdwi: number,
  structureConfidence: number,
  consistencyRaw: number,
  weights: ScoreWeights
): { composite: number; ndvi_gain: number; ndwi_presence: number; structure_evidence: number; consistency_factor: number } {
  // Normalize delta NDVI (-0.2 to +0.4) -> 0 to 100
  const normNdvi = Math.max(0, Math.min(100, Math.round(((deltaNdvi + 0.1) / 0.45) * 100)));
  // Normalize post NDWI (-0.4 to +0.4) -> 0 to 100
  const normNdwi = Math.max(0, Math.min(100, Math.round(((postNdwi + 0.3) / 0.65) * 100)));
  // Structure evidence -> 0 to 100
  const normStructure = Math.max(0, Math.min(100, Math.round(structureConfidence * 100)));
  // Consistency factor -> 0 to 100
  const normConsistency = Math.max(0, Math.min(100, Math.round(consistencyRaw * 100)));

  const composite = Math.round(
    weights.w1_ndvi * normNdvi +
    weights.w2_ndwi * normNdwi +
    weights.w3_structure * normStructure +
    weights.w4_consistency * normConsistency
  );

  return {
    composite: Math.max(0, Math.min(100, composite)),
    ndvi_gain: normNdvi,
    ndwi_presence: normNdwi,
    structure_evidence: normStructure,
    consistency_factor: normConsistency
  };
}

